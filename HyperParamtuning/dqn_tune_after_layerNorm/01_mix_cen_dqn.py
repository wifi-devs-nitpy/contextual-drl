def parse_args():
    p = argparse.ArgumentParser(
        description=(
            "Run LayerNorm HDQN using a generated "
            "hyperparameter configuration."
        )
    )

    p.add_argument(
        "--config-file",
        type=Path,
        default=Path(
            "./hdqn_hyperparameter_tuning/configs.csv"
        ),
        help="configs.csv generated by the tuner.",
    )

    group = p.add_mutually_exclusive_group()

    group.add_argument(
        "--config-id",
        type=str,
        default=None,
        help="Configuration ID from configs.csv.",
    )

    group.add_argument(
        "--config-index",
        type=int,
        default=None,
        help=(
            "1-based row/index in configs.csv "
            "(header not counted)."
        ),
    )

    group.add_argument(
        "--config-json",
        type=str,
        default=None,
        help=(
            "Configuration JSON produced by the tuner. "
            "Useful for direct programmatic hand-off."
        ),
    )

    # Scenario / experiment parameters.
    p.add_argument(
        "--d-ap",
        type=float,
        default=10.0,
    )

    p.add_argument(
        "--d-sta-1",
        type=int,
        default=2,
    )

    p.add_argument(
        "--d-sta-2",
        type=int,
        default=4,
    )

    p.add_argument(
        "--n-runs",
        type=int,
        default=50,
    )

    p.add_argument(
        "--n-steps",
        type=int,
        default=10_000,
    )

    p.add_argument(
        "--n-links",
        type=int,
        default=3,
    )

    p.add_argument(
        "--n-tx-power-levels",
        type=int,
        default=4,
    )

    p.add_argument(
        "--seed",
        type=int,
        default=42,
    )

    p.add_argument(
        "--window-size",
        type=int,
        default=100,
    )

    p.add_argument(
        "--step-duration",
        type=float,
        default=0.005,
    )

    p.add_argument(
        "--confidence",
        type=float,
        default=0.99,
    )

    p.add_argument(
        "--output-dir",
        type=Path,
        default=Path("./results"),
    )

    p.add_argument(
        "--filename",
        type=str,
        default=None,
    )

    p.add_argument(
        "--show",
        action="store_true",
    )

    return p.parse_args()


# ============================================================
# Reporting
# ============================================================

def print_configuration(cfg: dict):
    print("\n" + "=" * 100)
    print("HDQN CONFIGURATION")
    print("=" * 100)

    for i in range(4):
        print(
            f"L{i+1}: "
            f"optimizer={cfg['optimizer'][i]}, "
            f"lr={cfg['lr'][i]:.8g}, "
            f"buffer={cfg['buffer'][i]}, "
            f"batch={cfg['batch'][i]}, "
            f"replay_steps={cfg['replay_steps'][i]}, "
            f"epsilon_min={cfg['eps_min'][i]:.8g}, "
            f"epsilon_decay={cfg['eps_decay'][i]:.8g}, "
            f"weight_decay={cfg['weight_decay'][i]:.8g}"
        )

    print("=" * 100)


# ============================================================
# Main
# ============================================================

def main():
    args = parse_args()

    if args.n_runs < 1:
        raise ValueError("--n-runs must be >= 1.")

    if args.n_steps < 2:
        raise ValueError("--n-steps must be >= 2.")

    if not 0 < args.confidence < 1:
        raise ValueError(
            "--confidence must be between 0 and 1."
        )

    # JAX persistent compilation cache.
    jax.config.update(
        "jax_compilation_cache_dir",
        "./jax_cache",
    )
    jax.config.update(
        "jax_persistent_cache_enable_xla_caches",
        "all",
    )

    # --------------------------------------------------------
    # Load selected configuration.
    # --------------------------------------------------------
    if args.config_id is not None:
        cfg = read_config_from_csv(
            args.config_file,
            args.config_id,
        )
        config_label = args.config_id

    elif args.config_index is not None:
        cfg = read_config_by_index(
            args.config_file,
            args.config_index,
        )
        config_label = f"index_{args.config_index}"

    elif args.config_json is not None:
        cfg = normalize_config(
            json.loads(args.config_json)
        )
        config_label = "direct_json"

    else:
        cfg = baseline_configuration()
        config_label = "baseline"

    print_configuration(cfg)

    # --------------------------------------------------------
    # Scenario.
    # --------------------------------------------------------
    scenario = MixScen(
        small_office_scenario,
        args.d_sta_1,
        args.d_sta_2,
        args.d_ap,
        max_steps=args.n_steps,
    )

    # --------------------------------------------------------
    # Filename.
    # --------------------------------------------------------
    if args.filename is None:
        filename = (
            f"hdqn_{config_label}_"
            f"{scenario.str_repr}_"
            f"runs_{args.n_runs}_"
            f"steps_{args.n_steps}"
        )
    else:
        filename = args.filename

    # --------------------------------------------------------
    # Execute.
    # --------------------------------------------------------
    throughputs = run_experiments(
        scenario=scenario,
        cfg=cfg,
        args=args,
    )

    # --------------------------------------------------------
    # Existing throughput analysis / plotting.
    # --------------------------------------------------------
    analyze_and_plot_throughputs(
        throughputs=throughputs,
        window_size=args.window_size,
        step_duration=args.step_duration,
        confidence=args.confidence,
        output_dir=str(args.output_dir),
        filename=filename,
        show=args.show,
    )


if __name__ == "__main__":
    main()
