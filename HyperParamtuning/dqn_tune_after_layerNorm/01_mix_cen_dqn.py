# ============================================================
# Constants
# ============================================================

DEFAULT_D_AP = 10.0
DEFAULT_N_STEPS = 10_000

LEVELS = ("l1", "l2", "l3", "l4")


# ============================================================
# Mixed scenario
# ============================================================

class MixScen:
    def __init__(
        self,
        scenario_factory,
        d_sta_1: int,
        d_sta_2: int,
        d_ap: float = DEFAULT_D_AP,
        max_steps: int = DEFAULT_N_STEPS,
    ):
        self.scen1 = scenario_factory(
            d_ap=d_ap,
            d_sta=d_sta_1,
        )
        self.scen2 = scenario_factory(
            d_ap=d_ap,
            d_sta=d_sta_2,
        )

        self.step = 0
        self.switch_steps = max_steps // 2

        self.data_rate_fn1 = jax.jit(
            self.scen1.data_rate_fn
        )
        self.data_rate_fn2 = jax.jit(
            self.scen2.data_rate_fn
        )

        self.data_rate_fn = self.data_rate_fn1
        self.associations = self.scen1.associations

        self.str_repr = (
            f"mix_scen_ap_{d_ap:g}_"
            f"dsta_{d_sta_1}_{d_sta_2}_"
            f"s{max_steps}"
        )

    def __call__(self, key, link_ap_sta):
        self.step += 1

        if self.step == self.switch_steps:
            self.data_rate_fn = (
                self.data_rate_fn2
                if self.data_rate_fn is self.data_rate_fn1
                else self.data_rate_fn1
            )

        return self.data_rate_fn(
            key,
            link_ap_sta=link_ap_sta,
        )

    def reset(self):
        self.data_rate_fn = self.data_rate_fn1
        self.step = 0


