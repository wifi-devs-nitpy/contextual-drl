#!/usr/bin/env python3
"""
run_hdqn_experiment.py

Run the LayerNorm HDQN MAPC experiment using a generated hyperparameter
configuration.

The program can load a configuration generated by
`tune_hdqn_hyperparameters.py` from `configs.csv`:

    python run_hdqn_experiment.py \
        --config-id cfg_XXXXXXXXXXXXXXX \
        --config-file ./hdqn_hyperparameter_tuning/configs.csv

or by configuration row/index:

    python run_hdqn_experiment.py \
        --config-index 731 \
        --config-file ./hdqn_hyperparameter_tuning/configs.csv

It also accepts a configuration JSON directly, which is useful when the
tuner wants to launch a configuration without writing/reading a CSV.

Without --config-id / --config-index / --config-json, the exact original
baseline hyperparameters from the supplied experiment are used.

Important:
    - The HDQN architecture is not changed here.
    - LayerNorm remains wherever it is implemented in your QNetwork.
    - Only the hyperparameters passed through MapcDQNAgentFactory are changed.
    - Each run creates a fresh agent factory with a deterministic seed.
"""

