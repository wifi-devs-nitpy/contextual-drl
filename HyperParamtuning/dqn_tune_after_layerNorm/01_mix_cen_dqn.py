# ============================================================
# Configuration loading
# ============================================================

def normalize_config(cfg: dict) -> dict:
    """
    CSV JSON converts tuples to lists. Convert everything into the
    tuple-based representation expected by this runner.
    """
    required = {
        "optimizer",
        "lr",
        "buffer",
        "batch",
        "replay_steps",
        "eps_min",
        "eps_decay",
        "weight_decay",
    }

    missing = required.difference(cfg)
    if missing:
        raise ValueError(
            f"Configuration is missing fields: {sorted(missing)}"
        )

    normalized = {
        "optimizer": tuple(str(x) for x in cfg["optimizer"]),
        "lr": tuple(float(x) for x in cfg["lr"]),
        "buffer": tuple(int(x) for x in cfg["buffer"]),
        "batch": tuple(int(x) for x in cfg["batch"]),
        "replay_steps": tuple(int(x) for x in cfg["replay_steps"]),
        "eps_min": tuple(float(x) for x in cfg["eps_min"]),
        "eps_decay": tuple(float(x) for x in cfg["eps_decay"]),
        "weight_decay": tuple(float(x) for x in cfg["weight_decay"]),
    }

    for field, values in normalized.items():
        if len(values) != 4:
            raise ValueError(
                f"{field} must contain exactly 4 values, got {values}"
            )

    for i in range(4):
        if normalized["batch"][i] > normalized["buffer"][i]:
            raise ValueError(
                f"L{i+1}: batch size "
                f"{normalized['batch'][i]} exceeds replay buffer "
                f"{normalized['buffer'][i]}"
            )

        if normalized["lr"][i] <= 0:
            raise ValueError(
                f"L{i+1}: learning rate must be > 0."
            )

        if not 0 < normalized["eps_min"][i] <= 1:
            raise ValueError(
                f"L{i+1}: epsilon_min must be in (0, 1]."
            )

        if not 0 < normalized["eps_decay"][i] < 1:
            raise ValueError(
                f"L{i+1}: epsilon_decay must be in (0, 1)."
            )

    return normalized


def read_config_from_csv(config_file: Path, config_id: str) -> dict:
    if not config_file.exists():
        raise FileNotFoundError(
            f"Config file not found: {config_file}"
        )

    with config_file.open(
        "r",
        newline="",
        encoding="utf-8",
    ) as f:
        reader = csv.DictReader(f)

        for row in reader:
            if row["config_id"] == config_id:
                return normalize_config(
                    json.loads(row["configuration_json"])
                )

    raise ValueError(
        f"Configuration ID {config_id!r} was not found in "
        f"{config_file}"
    )


def read_config_by_index(config_file: Path, config_index: int) -> dict:
    if config_index < 1:
        raise ValueError(
            "--config-index is 1-based and must be >= 1."
        )

    with config_file.open(
        "r",
        newline="",
        encoding="utf-8",
    ) as f:
        reader = csv.DictReader(f)

        for row_number, row in enumerate(reader, start=1):
            if row_number == config_index:
                return normalize_config(
                    json.loads(row["configuration_json"])
                )

    raise ValueError(
        f"Configuration index {config_index} was not found in "
        f"{config_file}"
    )


# ============================================================
# Optimizer / agent construction
# ============================================================

def make_optimizer(
    name: str,
    learning_rate: float,
    weight_decay: float,
):
    name = name.lower()

    if name == "adam":
        return optax.adam(learning_rate)

    if name == "adamw":
        return optax.adamw(
            learning_rate=learning_rate,
            weight_decay=weight_decay,
        )

    raise ValueError(
        f"Unsupported optimizer {name!r}. "
        f"Expected 'adam' or 'adamw'."
    )


def make_agent_params(
    cfg: dict,
    level_index: int,
) -> dict:
    return {
        "optimizer": make_optimizer(
            cfg["optimizer"][level_index],
            cfg["lr"][level_index],
            cfg["weight_decay"][level_index],
        ),
        "experience_replay_buffer_size": (
            cfg["buffer"][level_index]
        ),
        "experience_replay_batch_size": (
            cfg["batch"][level_index]
        ),
        "experience_replay_steps": (
            cfg["replay_steps"][level_index]
        ),
        "epsilon_min": (
            cfg["eps_min"][level_index]
        ),
        "epsilon_decay": (
            cfg["eps_decay"][level_index]
        ),
    }


def create_agent_factory(
    scenario,
    cfg: dict,
    args,
    seed: int,
):
    """
    Feed generated per-level hyperparameters into the exact same
    MapcDQNAgentFactory used by the original program.
    """
    return MapcDQNAgentFactory(
        associations=scenario.associations,
        agent_params_lvl1=make_agent_params(cfg, 0),
        agent_params_lvl2=make_agent_params(cfg, 1),
        agent_params_lvl3=make_agent_params(cfg, 2),
        agent_params_lvl4=make_agent_params(cfg, 3),
        n_tx_power_levels=args.n_tx_power_levels,
        n_links=args.n_links,
        seed=seed,
    )


# ============================================================
# Experiment
# ============================================================

def run_single_experiment(
    scenario,
    cfg: dict,
    args,
    run_number: int,
    key,
):
    """
    One completely fresh HDQN run.

    The environment action/reward loop remains the same as in the
    supplied program:
        agent.sample(previous_reward)
        -> environment
        -> current reward becomes next previous_reward
    """
    factory = create_agent_factory(
        scenario=scenario,
        cfg=cfg,
        args=args,
        seed=args.seed + run_number,
    )

    agent = factory.create_hierarchical_DQN_cmapc_agent(
        logger=None
    )

    throughputs = np.zeros(
        args.n_steps,
        dtype=np.float32,
    )

    previous_throughput = 0.0

    scenario.reset()

    for step in tqdm(
        range(1, args.n_steps),
        desc=f"run_number: {run_number}",
        leave=True,
    ):
        key, step_key = jax.random.split(key)

        tx_config = agent.sample(
            reward=previous_throughput
        )

        data_rate = scenario(
            step_key,
            tx_config,
        )

        data_rate = float(data_rate)

        throughputs[step] = data_rate
        previous_throughput = data_rate

    return throughputs


def run_experiments(
    scenario,
    cfg: dict,
    args,
):
    """
    Every Monte-Carlo run gets a fresh factory/agent.

    The same JAX run keys are reused for the selected configuration,
    making it directly comparable with other configurations when the
    same seed is used.
    """
    run_keys = jax.random.split(
        jax.random.PRNGKey(args.seed),
        args.n_runs,
    )

    throughputs = np.zeros(
        (args.n_runs, args.n_steps),
        dtype=np.float32,
    )

    for run_number in range(args.n_runs):
        throughputs[run_number] = (
            run_single_experiment(
                scenario=scenario,
                cfg=cfg,
                args=args,
                run_number=run_number,
                key=run_keys[run_number],
            )
        )

    return throughputs


